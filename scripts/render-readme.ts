/**
 * Render the README's capability list and figures from the manifest (Sprint 31, WP-2).
 *
 * The README is the first document a stranger reads, and it is the one that drifts. Before this
 * script, its "Verified capabilities include:" list and several figures were typed by hand: they were
 * true on the day they were written and false the moment a capability shipped without an edit. The
 * audit that scoped this sprint found the README claiming a test count, a model locality, and a
 * throughput that no command reproduces.
 *
 * So the capability list is generated from `CAPABILITIES` — the same list the API route and the public
 * evidence page read — and `--check` fails if the committed README and the manifest disagree. The
 * marked block lives between `<!-- readme-capabilities:start ... -->` and `<!-- readme-capabilities:end -->`.
 *
 *   npm run render:readme            rewrite the marked section in README.md
 *   npm run render:readme -- --check fail (exit 1) if the README is out of date
 */
import fs from 'node:fs';
import path from 'node:path';
import { CAPABILITIES, type CapabilityEntry } from '../src/services/capabilityManifest';

export const README_CAPS_START =
  '<!-- readme-capabilities:start (generated by scripts/render-readme.ts; do not edit by hand) -->';
export const README_CAPS_END = '<!-- readme-capabilities:end -->';

/** Pure and deterministic: the same manifest always renders identically. */
export function renderReadmeCapabilitySection(entries: readonly CapabilityEntry[]): string {
  const rows = entries
    .map((entry) => {
      const demonstrated =
        entry.status === 'blocked'
          ? `blocked — owner: ${entry.owner}`
          : `\`${entry.proves}\`${entry.status === 'planned' ? ' (planned)' : ''}`;
      return `| ${entry.title} | ${entry.status} | ${demonstrated} |`;
    })
    .join('\n');
  const live = entries.filter((entry) => entry.status === 'live').length;
  const blocked = entries.filter((entry) => entry.status === 'blocked').length;
  const planned = entries.filter((entry) => entry.status === 'planned').length;
  return [
    README_CAPS_START,
    '| Capability | Status | Demonstrated by / owner |',
    '|---|---|---|',
    rows,
    '',
    `**${live} live · ${blocked} blocked · ${planned} planned.** Every live entry names the command that`,
    'demonstrates it; every blocked entry names the operator who must unblock it. A capability appears',
    'here only when it is declared in `src/services/capabilityManifest.ts` — this table is generated by',
    '`npm run render:readme`, so it cannot describe a capability the code does not.',
    README_CAPS_END,
  ].join('\n');
}

function replaceSection(readme: string, section: string): string {
  const start = readme.indexOf(README_CAPS_START);
  const end = readme.indexOf(README_CAPS_END);
  if (start < 0 || end < 0 || end < start) {
    throw new Error('README.md is missing the readme-capabilities markers');
  }
  return readme.slice(0, start) + section + readme.slice(end + README_CAPS_END.length);
}

function main(): void {
  const file = path.join(process.cwd(), 'README.md');
  const readme = fs.readFileSync(file, 'utf8');
  const rendered = renderReadmeCapabilitySection(CAPABILITIES);
  const next = replaceSection(readme, rendered);
  if (process.argv.includes('--check')) {
    if (next !== readme) {
      process.stderr.write(
        'README.md is out of date with the capability manifest. Run: npm run render:readme\n',
      );
      process.exit(1);
    }
    process.stdout.write('README.md capability section matches the manifest.\n');
    return;
  }
  fs.writeFileSync(file, next);
  process.stdout.write('README.md capability section rendered from the manifest.\n');
}

if (process.argv[1] && path.resolve(process.argv[1]).endsWith('render-readme.ts')) main();
