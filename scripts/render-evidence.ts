/**
 * Render the public evidence page's capability section from the capability manifest (Sprint 30, WP-5).
 *
 * The evidence page must state what is live, planned, or blocked, and every live item must name the
 * command that demonstrates it. The failure mode is drift: the page claiming a capability, or a
 * status, that the manifest does not declare — or the manifest gaining a capability the page never
 * mentions. So the section is generated from `CAPABILITIES`, the same list the API serves, and
 * `--check` fails if the committed page and the manifest disagree. A page nobody regenerates is a
 * page that lies.
 *
 *   npm run render:evidence            rewrite the marked section in site/index.html
 *   npm run render:evidence -- --check fail (exit 1) if the page is out of date
 *
 * The section lives between `<!-- capabilities:start -->` and `<!-- capabilities:end -->`. The
 * rendered block carries the manifest as JSON (so a test can assert exact equality) above a human
 * table.
 */
import fs from 'node:fs';
import path from 'node:path';
import { CAPABILITIES, type CapabilityEntry } from '../src/services/capabilityManifest';

export const CAPABILITIES_START = '<!-- capabilities:start (generated by scripts/render-evidence.ts; do not edit by hand) -->';
export const CAPABILITIES_END = '<!-- capabilities:end -->';

/** Pure: the marked block for a manifest. Deterministic — the same list always renders identically. */
export function renderCapabilitySection(entries: readonly CapabilityEntry[]): string {
  const label: Record<CapabilityEntry['status'], string> = { live: 'live', planned: 'planned', blocked: 'blocked' };
  const rows = entries.map((entry) => {
    const proof = entry.status === 'blocked'
      ? `<span class="no">blocked</span>`
      : `<span class="ok">${label[entry.status]}</span>`;
    const demonstrated = entry.status === 'blocked'
      ? `blocked — owner: ${entry.owner}`
      : `<code>${entry.proves}</code>${entry.status === 'planned' ? ' (planned)' : ''}`;
    return `    <tr><td>${entry.title}</td><td>${proof}</td><td>${demonstrated}</td></tr>`;
  }).join('\n');
  const json = JSON.stringify(entries, null, 2);
  return [
    CAPABILITIES_START,
    '  <h2>Capabilities</h2>',
    '  <p>What this build can do, and the command or route that demonstrates each one. A capability is listed only when the code declares it; a blocked one names the person who must unblock it.</p>',
    '  <script type="application/json" id="capability-manifest">',
    json,
    '  </script>',
    '  <table>',
    '    <tr><th>Capability</th><th>Status</th><th>Demonstrated by / owner</th></tr>',
    rows,
    '  </table>',
    CAPABILITIES_END,
  ].join('\n');
}

function replaceSection(html: string, section: string): string {
  const start = html.indexOf(CAPABILITIES_START);
  const end = html.indexOf(CAPABILITIES_END);
  if (start < 0 || end < 0 || end < start) throw new Error('site/index.html is missing the capabilities markers');
  return html.slice(0, start) + section + html.slice(end + CAPABILITIES_END.length);
}

function main(): void {
  const file = path.join(process.cwd(), 'site', 'index.html');
  const html = fs.readFileSync(file, 'utf8');
  const rendered = renderCapabilitySection(CAPABILITIES);
  const next = replaceSection(html, rendered);
  if (process.argv.includes('--check')) {
    if (next !== html) {
      process.stderr.write('site/index.html is out of date with the capability manifest. Run: npm run render:evidence\n');
      process.exit(1);
    }
    process.stdout.write('site/index.html capability section matches the manifest.\n');
    return;
  }
  fs.writeFileSync(file, next);
  process.stdout.write('site/index.html capability section rendered from the manifest.\n');
}

if (process.argv[1] && path.resolve(process.argv[1]).endsWith('render-evidence.ts')) main();
