/**
 * Generate `docs/audit/CODEBASE-INDEX.md` from the tracked tree (Sprint 31, WP-2).
 *
 * A hand-written index of the repository is the second thing to drift, after the README: it lists
 * files that were renamed and omits directories that appeared. This one is generated from
 * `git ls-files`, so it describes exactly the committed tree and nothing else, and `--check` fails
 * when it is stale.
 *
 *   npm run render:codebase-index            rewrite docs/audit/CODEBASE-INDEX.md
 *   npm run render:codebase-index -- --check fail (exit 1) if the index is out of date
 *
 * Deterministic: file lists are sorted, so the same tree always renders identically.
 */
import fs from 'node:fs';
import path from 'node:path';
import { execFileSync } from 'node:child_process';

const INDEX_FILE = path.join('docs', 'audit', 'CODEBASE-INDEX.md');

function listTrackedFiles(): string[] {
  const out = execFileSync('git', ['ls-files'], { encoding: 'utf8' });
  return out.split('\n').filter((line) => line.length > 0);
}

function countByTopLevel(files: readonly string[]): Array<{ dir: string; count: number }> {
  const counts = new Map<string, number>();
  for (const file of files) {
    const slash = file.indexOf('/');
    const dir = slash === -1 ? '(root files)' : file.slice(0, slash);
    counts.set(dir, (counts.get(dir) ?? 0) + 1);
  }
  return [...counts.entries()]
    .map(([dir, count]) => ({ dir, count }))
    .sort((a, b) => b.count - a.count || a.dir.localeCompare(b.dir));
}

function filesIn(files: readonly string[], prefix: string, suffix: string): string[] {
  return files
    .filter((file) => file.startsWith(prefix) && file.endsWith(suffix))
    .sort((a, b) => a.localeCompare(b));
}

function renderList(items: readonly string[], empty: string): string {
  if (items.length === 0) return `_${empty}_`;
  return items.map((item) => `- \`${item}\``).join('\n');
}

/** Pure and deterministic: the same tracked tree always renders identically. */
export function renderCodebaseIndex(files: readonly string[]): string {
  const byDir = countByTopLevel(files);
  const services = filesIn(files, 'src/services/', '.ts');
  const routes = filesIn(files, 'src/api/routes/', '.ts');
  const tests = filesIn(files, 'test/', '.test.ts');
  const scripts = filesIn(files, 'scripts/', '');
  const doctrine = filesIn(files, 'doctrine/', '');
  const docs = filesIn(files, 'docs/', '.md');
  const sprints = filesIn(files, 'sprints/', '.md');
  const adrs = filesIn(files, 'docs/adr/', '.md');

  const dirRows = byDir
    .map(({ dir, count }) => `| \`${dir}\` | ${count} |`)
    .join('\n');

  return [
    '# Codebase Index',
    '',
    '> Generated by `npm run render:codebase-index` from `git ls-files`. Do not edit by hand;',
    '> `npm run render:codebase-index -- --check` fails when this file and the tree disagree.',
    '',
    `**Tracked files:** ${files.length}. **Services:** ${services.length}. **API route modules:** ${routes.length}. **Tests:** ${tests.length}. **Scripts:** ${scripts.length}. **Doctrine files:** ${doctrine.length}. **ADRs:** ${adrs.length}. **Documented pages under docs/:** ${docs.length}. **Sprint records:** ${sprints.length}.`,
    '',
    '## Tracked files by top-level directory',
    '',
    '| Directory | Files |',
    '|---|---:|',
    dirRows,
    '',
    '## Services (`src/services/`)',
    '',
    renderList(services, 'No services found.'),
    '',
    '## API route modules (`src/api/routes/`)',
    '',
    renderList(routes, 'No route modules found.'),
    '',
    '## Tests (`test/*.test.ts`)',
    '',
    renderList(tests, 'No tests found.'),
    '',
    '## Scripts (`scripts/`)',
    '',
    renderList(scripts, 'No scripts found.'),
    '',
    '## Doctrine (`doctrine/`)',
    '',
    renderList(doctrine, 'No doctrine files found.'),
    '',
    '## Architecture Decision Records (`docs/adr/`)',
    '',
    renderList(adrs, 'No ADRs found.'),
    '',
  ].join('\n');
}

function main(): void {
  const index = renderCodebaseIndex(listTrackedFiles());
  const file = path.join(process.cwd(), INDEX_FILE);
  const current = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : '';
  if (process.argv.includes('--check')) {
    if (current !== index) {
      process.stderr.write(
        `${INDEX_FILE} is out of date with the tracked tree. Run: npm run render:codebase-index\n`,
      );
      process.exit(1);
    }
    process.stdout.write(`${INDEX_FILE} matches the tracked tree.\n`);
    return;
  }
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, index);
  process.stdout.write(`${INDEX_FILE} rendered from the tracked tree.\n`);
}

if (process.argv[1] && path.resolve(process.argv[1]).endsWith('render-codebase-index.ts')) main();
